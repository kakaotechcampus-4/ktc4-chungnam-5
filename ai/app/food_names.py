"""사진 분석 음식명의 검증된 동의 표기를 DB 검색에 쓰는 이름으로 모은다.

전체 이름이 등록된 동의어일 때만 바꾼다. 재료·조리법·상품명·복합 음식의 일부를
지우거나 다른 음식으로 추정하지 않는다. DB의 어휘를 맞추는 후처리이며, 실제
사진의 레시피나 영양값이 그 DB 항목과 같다는 보장은 아니다. DB 조회는 BE가 한다.

2026-11-09 공공 DB snapshot에서 확인한 7개 음식군만 포함한다. 특히 스프는
재료와 종류를 띄어 써야 BE 토큰 검색이 ``스프_양송이버섯`` 같은 항목도 찾는다.
근거와 전후 비교는 ``manual_feedback/food_name_p2_20261109``에 보관한다.
"""

from __future__ import annotations

import unicodedata


_FAMILIES = (
    ("망고주스", ("망고주스", "망고 주스", "망고쥬스", "망고 쥬스")),
    ("리치주스", ("리치주스", "리치 주스", "리치쥬스", "리치 쥬스")),
    ("토마토주스", ("토마토주스", "토마토 주스", "토마토쥬스", "토마토 쥬스")),
    ("양송이 스프", ("양송이스프", "양송이 스프", "양송이수프", "양송이 수프")),
    ("크림 스프", ("크림스프", "크림 스프", "크림수프", "크림 수프")),
    ("옥수수 스프", ("옥수수스프", "옥수수 스프", "옥수수수프", "옥수수 수프")),
    (
        "달걀후라이",
        (
            "달걀프라이", "달걀 프라이", "달걀후라이", "달걀 후라이",
            "계란프라이", "계란 프라이", "계란후라이", "계란 후라이",
        ),
    ),
)
_ALIASES = {alias: canonical for canonical, aliases in _FAMILIES for alias in aliases}


def normalize_food_name(name: str) -> str:
    """검증된 전체 음식명의 표기만 바꾸고, 미등록 입력은 원문 그대로 반환한다.

    Unicode와 연속 공백 정리는 별칭을 찾을 때만 적용한다. 모든 공백을 지우면
    BE의 토큰 검색 의미가 바뀌므로 단어 경계를 임의로 합치지 않는다.
    """
    lookup = " ".join(unicodedata.normalize("NFC", name).split())
    return _ALIASES.get(lookup, name)
