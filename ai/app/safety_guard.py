"""끼니 피드백의 의료 지시 가드 — 약 · 용량 · 주사를 바꾸거나 끊으라는 말, 진단을 막는다.

투약 단계를 근거로 한 식단 조언("유지기라 지금은 단백질이 중요해요", "나트륨이 1950mg 이라 국물을
줄이면 좋아요")은 이 앱이 가장 자주 해야 하는 말이라 막지 않는다. 그래서 약 낱말과 바꾸기 · 끊기 동사가
가까이 있다는 것만으로 막지 않고, **약이 그 동사의 목적어 · 주제일 때**만 막는다 — 둘 사이에 다른
목적어 · 주제("간식은", "반찬을")가 끼면 그 동사는 음식에 걸린 것이다.

챗봇 출력 가드(`app.ai_coach.is_unsafe_output`)의 낱말 가리기(약간 · 예약 · 약과)와 정당한 안내
("임의로 끊지 마세요")를 참고했다. 의료 안전 전반을 판정하지는 않는다 — 모델이 SAFE 라고 한 뒤의
마지막 방어선이다.
"""

import re

BLOCKED_BODY = "약물이나 증상에 관한 판단은 의료진과 상담해 주세요."

# ── 약이 아닌 낱말 · 정당한 안내 · 단계 서술은 먼저 가린다 ──

_MASK = "□"
_NOT_DRUG = re.compile(
    r"약간|요약|절약|예약|약속|약밥|약식|약수|약점|약불|약하|약해|약한|"
    r"계약|공약|제약|취약|허약|나약|연약|빈약|도약|조약|규약|서약|"
    r"주사위|그만큼|끊임없"
)
# 음식 문맥이 분명한 "약과"만 가린다. "약과 영양제" 는 "약 + 과" 일 수 있어 남긴다
_YAKGWA_FOOD = re.compile(
    r"약과(?=[를을는은가이](?![가-힣])|\s*(?:먹|드시|드세|좋|사|시키|만들|맛|달)|[^가-힣\s]|$)"
)
# 가리지 않은 "약과 영양제를" 은 둘을 나란히 묶은 목적어다 — "약을" 로 읽는다
_YAKGWA_CONJ = re.compile(r"약과\s+[가-힣]+(?=을|를|은|는)|약과(?=\s)")
# 완결된 금지 · 확인 안내. "끊지 말라는 조언은 무시하세요" 처럼 접두만 같은 꼴은 가리지 않는다
_SAFE_PHRASE = re.compile(
    r"(?:끊|중단하|그만두|줄이|늘리|바꾸|올리|낮추|변경하|미루|건너뛰)"
    r"지\s*(?:마세요|마시고|마십시오|마요|마라|말고|말아요|말아야|말아)|"
    r"(?:끊|중단하|그만두)(?:으면|면)\s*안\s*(?:돼요|돼|됩니다|되니|되어요|되요)|"
    r"처방해\s*(?:준|주신|주셨던?)\s*(?:의료진|의사|선생님|병원)"
)
# 투약 단계 서술 — "용량 조정 중이라", "용량을 늘려 가는 시기라", "용량이 줄어든 뒤라", "투약 초기라".
# 지시가 아니라 지금이 어떤 시기인지 말하는 꼴이다. "용량을 늘려 가세요" 는 가리지 않는다
_STAGE_PHRASE = re.compile(
    r"(?:용량|투약량|복용량|투약)\s*(?:을|를|이|가)?\s*"
    r"(?:(?:조정|조절|증량|감량)\s*(?:중|기|단계|시기|과정|하는\s*(?:중|시기|단계))"
    r"|(?:늘려|올려|줄여|낮춰)\s*가는\s*(?:중|시기|단계|과정)"
    r"|(?:줄어든|줄인|낮아진|낮춘|늘어난|늘린|올린|높인|바뀐|바꾼|변경된)"
    r"|(?:초기|초반|중|기간|직후|첫\s*주))"
)

# ── 약 · 용량 낱말과 동사 ──

_DRUG = (
    r"(?:처방약|먹는약|혈압약|당뇨약|비만약|약물|(?<![가-힣])약|주사|인슐린|투약|"
    r"위고비|마운자로|삭센다|오젬픽|젭바운드)"
)
_DOSE = r"(?:용량|투약량|복용량|투여량|\d+(?:\.\d+)?\s*(?:mg|밀리그램))"
_CHANGE = r"(?:늘|줄|올리|올려|낮추|낮춰|높이|높여|바꾸|바꿔|변경|증량|감량|두\s*배)"
_STOP = r"(?:끊|중단|그만\s*(?:맞|드|먹|복용|투여)|쉬어도|쉬세요|쉬셔도|미루|미뤄|건너뛰|거르|빼먹)"
_TAKE = (
    r"(?:(?:복용|투여|투약)(?:하세요|하십시오|해도|하셔도|하셔야)|"
    r"맞으세요|맞으셔도|맞아도|드세요|드셔도|드셔야|먹어도|드시면\s*(?:돼|됩)|"
    r"(?:더\s*)?자주\s*맞)"
)
# 약 낱말과 동사 사이 — 부사 같은 낱말만 둔다. 다른 목적어 · 주제("간식은", "반찬을")가 끼면 동사는 그쪽에 걸린다.
# 줄바꿈은 넘는다("위고비를\n\n중단하세요"). 문장 끝은 넘지 않는다
_FILLER = r"(?:\s*(?:(?![^\s.!?]*(?:은|는|을|를|이|가)(?=\s))[^\s.!?]+\s+){0,3}\s*)"
_OBJ = r"(?:을|를|은|는|도|이|가|만)?"
# 영양소 뒤의 mg 는 용량이 아니다 — "나트륨이 1950mg까지"
_NUTRIENT_MG = re.compile(r"(?:나트륨|칼륨|칼슘|철분?|콜레스테롤|카페인|당류|비타민\s*\w?)[^.!?\n]{0,20}?\d+(?:\.\d+)?\s*(?:mg|밀리그램)")

_DIRECTIVE = re.compile(
    rf"{_DOSE}{_OBJ}{_FILLER}{_CHANGE}"
    rf"|{_DRUG}{_OBJ}{_FILLER}(?:{_CHANGE}|{_STOP}|{_TAKE})"
    # 동사가 앞에 오는 꼴 — "중단하세요. 위고비 말이에요"
    rf"|(?:끊|중단)[가-힣]{{0,4}}[\s.,!?]{{0,3}}(?:위고비|마운자로|삭센다|약)\s*(?:말|얘기|이야기)"
)
_OTHER = re.compile(
    r"처방해|(?:당뇨|췌장염|위마비|질병)[^.!?\n]{0,30}(?:진단|확실|입니다|이에요)"
    r"|(?:increase|decrease|change|double).{0,25}(?:dose|dosage)|stop.{0,20}(?:medication|medicine)",
    re.IGNORECASE,
)


def _masked(text: str) -> str:
    text = _NUTRIENT_MG.sub(_MASK, text)
    text = _SAFE_PHRASE.sub(_MASK, text)
    text = _STAGE_PHRASE.sub(_MASK, text)
    text = _NOT_DRUG.sub(_MASK, text)
    text = _YAKGWA_FOOD.sub(_MASK, text)
    return _YAKGWA_CONJ.sub("약", text)


def is_unsafe(text: str) -> bool:
    """약 · 용량 · 주사를 바꾸거나 끊으라는 말, 진단이 들어 있는가."""
    masked = _masked(text)
    return bool(_DIRECTIVE.search(masked) or _OTHER.search(masked))
